def user_message(source: SourceFile, max_chars: int) -> tuple[str, int]:
    rows: list[str] = []
    size = 0
    for n, line in enumerate(source_lines(source.text), 1):
        row = f"{n:>5} | {line}"
        size += len(row) + 1
        if size > max_chars:
            break
        rows.append(row)
    text = f"Файл: /{source.name}\nСтрок: {source.lines}\n\nПронумерованный листинг:\n"
    text += "\n".join(rows)
    if len(rows) < source.lines:
        text += (
            f"\n\nЛистинг обрезан на строке {len(rows)} из {source.lines}. "
            f"Остальное прочитай инструментом read_file по пути /{source.name}."
        )
    return text, len(rows)
